/**
 * 한국어 문장에서 Kano 설문에 사용할 핵심 토픽(명사구)을 추출합니다.
 * 서술어와 종결 어미를 제거하여 질문 문구가 매끄러워지도록 합니다.
 * 
 * @param requirement 원본 요구사항 문장
 * @returns 추출된 핵심 토픽
 */
export function getKanoTopic(requirement: string): string {
    if (!requirement) return '';

    let topic = requirement.trim();

    // 1. 특정 패턴 제거 (끝에서부터 확인)
    const patterns = [
        /(었|였|했)으면 좋겠다$/,
        /(었|였|했)으면 좋겠음$/,
        /면 좋겠다$/,
        /면 좋겠음$/,
        /해야 한다$/,
        /해야 함$/,
        /해야 하함$/, // 오타 대비
        /할 것$/,
        /할 수 있음$/,
        /할 수 있다$/,
        /을 제공함$/,
        /를 제공함$/,
        /을 지원함$/,
        /를 지원함$/,
        /기능이 필요함$/,
        /기능이 있으면 좋겠다$/,
        /이 필요함$/,
        /가 필요함$/,
        /을 확보함$/,
        /를 확보함$/,
        /을 구현함$/,
        /를 구현함$/,
        /을(를) 통해 (.*)을(를) 얻고자 함$/,
        /을 통해 (.*)을 얻고자 함$/,
        /를 통해 (.*)를 얻고자 함$/,
        /을(를) 얻고자 함$/,
        /을 얻고자 함$/,
        /를 얻고자 함$/,
        /있었으면 함$/,
        / 있으면 함$/,
        / 있음$/,
        / 있다$/,
        / 이다$/,
        / 임$/,
        /기$/, // 명사화 종결어미 (예: '속도가 빠르기')
        /함$/,  // 명사화 종결어미 (예: '배터리가 오래 감')
        /다$/,  // 평서문 종결어미 (예: '디자인을 개선한다')
    ];

    for (const pattern of patterns) {
        if (pattern.test(topic)) {
            // 패턴 매핑 시 뒷부분 제거
            topic = topic.replace(pattern, '').trim();
            break; 
        }
    }

    // 2. 불필요한 조사 정리 (마지막에 남은 것들)
    topic = topic.replace(/[을를이가은는]$/, '').trim();

    // 3. 만약 너무 짧아지면 원본 반환 (안전을 위해)
    if (topic.length < 2) return requirement.trim();

    return topic;
}
